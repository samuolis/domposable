#!/usr/bin/env python3
"""Build readable component and modifier references from Dokka's compiled API model."""
from __future__ import annotations
import argparse
import html
from html.parser import HTMLParser
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
API_URL = 'https://samuolis.github.io/domposable/api/'

class Signature(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.depth = 0
        self.symbol_depth = None
        self.parameter_depth = None
        self.symbols = []
        self.parameters = []
        self.symbol = []
        self.parameter = []
    def handle_starttag(self, tag, attrs):
        if tag in {'br', 'hr', 'img', 'input', 'link', 'meta', 'wbr'}:
            return
        self.depth += 1
        classes = dict(attrs).get('class', '').split()
        if 'symbol' in classes and 'monospace' in classes:
            self.symbol_depth = self.depth
            self.symbol = []
        if self.symbol_depth is not None and 'parameter' in classes:
            if self.parameter_depth is not None:
                raise ValueError('Unexpected nested Dokka parameter markup')
            self.parameter_depth = self.depth
            self.parameter = []
    def handle_endtag(self, tag):
        if tag in {'br', 'hr', 'img', 'input', 'link', 'meta', 'wbr'}:
            return
        if self.depth == self.parameter_depth:
            value = re.sub(r'\s+', ' ', ''.join(self.parameter)).strip().rstrip(', ')
            self.parameters.append(value)
            self.parameter_depth = None
        if self.depth == self.symbol_depth:
            self.symbols.append(re.sub(r'\s+', ' ', ''.join(self.symbol)).strip())
            self.symbol_depth = None
        self.depth -= 1
    def handle_data(self, text):
        if self.symbol_depth is not None:
            self.symbol.append(text)
        if self.parameter_depth is not None:
            self.parameter.append(text)

def signature(path):
    parser = Signature()
    parser.feed(path.read_text())
    if not parser.symbols:
        raise ValueError(f'Missing Dokka signature: {path}')
    return parser

def slug(name):
    return '-' + re.sub(r'(?<!^)(?=[A-Z])', '-', name).lower()

def code(value):
    return '`' + value.replace('|', '&#124;').replace('`', '&#96;') + '`'

def parameter(value):
    name, colon, rest = value.partition(': ')
    kind, equals, default = rest.partition(' = ')
    if not colon or not name or not kind:
        raise ValueError(f'Unexpected Dokka parameter: {value}')
    return name, kind, default if equals else None

def linked_type(kind, root):
    def link(match):
        name = match.group()
        for module, package in [('domposable-foundation', 'io.github.samuolis.domposable.foundation'), ('domposable-ui', 'io.github.samuolis.domposable.ui')]:
            target = f'{module}/{package}/{slug(name)}/index.html'
            if (root/'build/dokka/html'/target).exists():
                return f'<a href="{API_URL}{target}">{name}</a>'
        return name
    return '<code>' + re.sub(r'Domposable\w+', link, html.escape(kind).replace('|', '&#124;')) + '</code>'

def references(root=ROOT):
    source = root / 'domposable-ui/src/commonMain/kotlin/io/github/samuolis/domposable/ui'
    api = root / 'build/dokka/html/domposable-ui/io.github.samuolis.domposable.ui'
    catalog = json.loads((root / 'catalog/material3.json').read_text())
    categories = {entry['component']: entry['category'] for entry in catalog['components']}
    components = {}
    pattern = re.compile(r'@DomposableComponent\("(\w+)"\)\s*(?:@[^\n]+\n\s*)*(?:data\s+)?class\s+(\w+)')
    for path in sorted(source.glob('*.kt')):
        text = path.read_text()
        matches = list(pattern.finditer(text))
        if len(matches) != text.count('@DomposableComponent('):
            raise ValueError(f'Unrecognized component declaration in {path}')
        for match in matches:
            name, props = match.groups()
            if name in components:
                raise ValueError(f'Duplicate component: {name}')
            components[name] = (props, path, match.start())
    if not components or not set(categories).issubset(components):
        raise ValueError('Component inventory is empty or missing a Material family')
    lines = ['# Component parameter reference', '', '<!-- Generated by scripts/ci/api_reference.py; do not edit tables by hand. -->', '',
        f'All **{len(components)} renderer contracts** below are supported by the native Compose and HTML providers. Wasm uses the Compose UI provider. See [platform behavior and limits](coverage.md) and [Material variants](material-catalog.md).', '',
        'Feature code can use direct arguments. These tables describe the canonical `Props` models; direct overloads add `modifier` and composable content slots where appropriate. The linked API pages contain all overloads and related appearance types.', '',
        '## Parameter conventions', '',
        '- Values and selection are controlled by the app; callbacks report requested changes.',
        '- Form controls inherit an enclosing disabled form state.',
        '- `label`, `description` and image descriptions provide accessible naming; visual headings are explicit.',
        '- A null `appearance` uses the family theme style. Copy that style for a partial override.',
        '- `modifier` configures layout/drawing/semantics; content and icon slots accept shared composables.', '',
        '## Index', '', '| Component | Family | Parameters |', '| --- | --- | ---: |']
    sections = []
    for name, (props, path, offset) in sorted(components.items()):
        folder = slug(props)
        model = signature(api / folder / f'{folder}.html')
        params = list(dict.fromkeys(model.parameters))
        if not params:
            raise ValueError(f'No constructor parameters for {props}')
        family = categories.get(name, 'Core / additional controls')
        lines.append(f'| [Domposable{name}](#domposable{name.lower()}) | {family} | {len(params)} |')
        relative = path.relative_to(root).as_posix()
        line = path.read_text()[:offset].count('\n') + 1
        sections.extend([f'## Domposable{name}', '',
            f'{family}. [Full API and overloads]({API_URL}domposable-ui/io.github.samuolis.domposable.ui/{slug("Domposable" + name)}.html) · [Props API]({API_URL}domposable-ui/io.github.samuolis.domposable.ui/{folder}/index.html) · [Source](https://github.com/samuolis/domposable/blob/main/{relative}#L{line})', '',
            '| Parameter | Type | Default |', '| --- | --- | --- |'])
        for value in params:
            key, kind, default = parameter(value)
            sections.append(f'| {code(key)} | {linked_type(kind, root)} | {code(default) if default is not None else "**Required**"} |')
        sections.append('')
    lines.extend([''] + sections)
    names = sorted(set(re.findall(r'^fun DomposableModifier\.(\w+)\(', (source/'Modifier.kt').read_text(), re.MULTILINE)))
    modifier = ['# Modifier API reference', '', '<!-- Generated by scripts/ci/api_reference.py; do not edit signatures by hand. -->', '',
        'These shared operations work on native Compose and HTML; Wasm uses Compose UI. See [modifier recipes and support boundaries](modifiers.md) for custom CSS, native drawing and app-owned decoration.', '']
    for name in names:
        page = re.sub(r'(?<!^)(?=[A-Z])', '-', name).lower() + '.html'
        model = signature(api/page)
        modifier.extend([f'## {name}', '', '```kotlin', *dict.fromkeys(model.symbols), '```', ''])
    return {'component-reference.md': '\n'.join(lines), 'modifier-reference.md': '\n'.join(modifier)}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--output-dir', type=Path, help='Export compiled references for review without replacing checked-in docs')
    args = parser.parse_args()
    output = args.output_dir or ROOT/'docs'
    if not args.check:
        output.mkdir(parents=True, exist_ok=True)
    for name, content in references().items():
        path = output/name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'{path.relative_to(ROOT)} is stale. Run ./gradlew dokkaGenerate then python3 scripts/ci/api_reference.py')
        else:
            path.write_text(content)
        print(f'{"Verified" if args.check else "Generated"} {path}')

if __name__ == '__main__':
    main()
